# English build: find every Bible reference in the translated sources and fill it from the KJV (public domain),
# cross-checked between two independent KJV datasets. Unverified verses are left out of the app.
import re, json, sys, os, datetime
sys.path.insert(0, '/workspace/v3src'); import i18n
D = '/workspace/v3src/'; K = '/workspace/bible/kjv/'
BOOKS = json.load(open(K + 'Bible-kjv-master/Books.json'))
TH = json.load(open(K + 'thiago.json', encoding='utf-8-sig'))
def arul(book, c, v):
    f = K + 'Bible-kjv-master/' + book.replace(' ', '') + '.json'
    j = json.load(open(f))
    for ch in j['chapters']:
        if int(ch['chapter']) == c:
            for x in ch['verses']:
                if int(x['verse']) == v: return x['text']
def thia(book, c, v):
    b = TH[BOOKS.index(book)]
    try: return b['chapters'][c - 1][v - 1]
    except IndexError: return None
NAMES = sorted(set(BOOKS) | {'Psalm'}, key=len, reverse=True)
pat = re.compile(r'\b(' + '|'.join(map(re.escape, NAMES)) + r') (\d+):(\d+)(?:-(\d+))?')
def norm(s): return re.sub(r'[^a-z]', '', re.sub(r'\{[^}]*\}', lambda m: m.group(0)[1:-1], (s or '').lower()))
def clean(s): return re.sub(r'\s+', ' ', re.sub(r'[{}]', '', s)).strip()
refs = set()
for p in ['data.js', 'word.js', 'core.js', 'onboard.js', 'main.js', 'journey.js', 'music.js', 'health.js', 'extra.js']:
    src, miss, _ = i18n.translate(p, open(D + p, encoding='utf-8').read())
    for m in pat.finditer(src): refs.add(m.group(0))
rows, OUT = [], {}
def key(r):
    m = pat.match(r); b = 'Psalms' if m.group(1) == 'Psalm' else m.group(1); return (BOOKS.index(b), int(m.group(2)), int(m.group(3)))
for r in sorted(refs, key=key):
    m = pat.match(r); b = 'Psalms' if m.group(1) == 'Psalm' else m.group(1); c, a = int(m.group(2)), int(m.group(3)); z = int(m.group(4) or a)
    A = [arul(b, c, v) for v in range(a, z + 1)]; T = [thia(b, c, v) for v in range(a, z + 1)]
    ok = all(A) and all(T) and all(norm(x) == norm(y) for x, y in zip(A, T))
    txt = ' '.join(clean(x) for x in A) if all(A) else ''
    if ok: OUT[r] = txt
    rows.append((r, ok, txt))
open(D + 'en/kjv.gen.js', 'w', encoding='utf-8').write('// Auto-generated by kjv.py — King James Version (public domain), cross-checked against two KJV datasets\nconst KRV = ' + json.dumps(OUT, ensure_ascii=False, indent=0) + ';\n')
bad = [r for r in rows if not r[1]]
md = ['# Scripture sources and verification (King James Version, public domain)', '',
      'Every verse in the English app is found automatically in the source by `v3src/kjv.py` at build time, checked verse by verse against two independent public-domain KJV datasets, and inserted **word for word**. A verse that fails the check is left out of the app (never guessed).', '',
      '## Sources', '', '1. aruljohn/Bible-kjv (KJV, public domain): https://github.com/aruljohn/Bible-kjv (text shown in the app)',
      '2. thiagobodruk/bible `json/en_kjv.json` (KJV, public domain): https://github.com/thiagobodruk/bible', '',
      'Rule: VERIFIED when both texts are identical letter for letter (ignoring spaces, punctuation and case).', '',
      f'Checked: {datetime.date.today().isoformat()} · {len(rows)} references · verified {len(rows) - len(bad)} · excluded {len(bad)}', '',
      '| Reference | Result | KJV text |', '|---|---|---|']
for r, ok, t in rows: md.append(f'| {r} | {"✅ verified" if ok else "❌ excluded"} | {t} |')
os.makedirs('/workspace/purify-site-en/tools', exist_ok=True)
open('/workspace/purify-site-en/tools/verses-source.md', 'w', encoding='utf-8').write('\n'.join(md) + '\n')
print(f'KJV verses: {len(rows)} total, {len(rows) - len(bad)} verified, {len(bad)} excluded')
for r in bad: print('  EXCLUDED', r[0], r[2][:80])
